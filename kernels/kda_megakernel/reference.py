"""Sequential PyTorch reference for the complete forward KDA module.

The core uses the token recurrence, not a low-precision chunk inverse.
Inputs and outputs are explicit; only out and final_state are modified.
"""

from __future__ import annotations

import math

import torch
import torch.nn.functional as F


def validate_arguments(
    inpx, in_proj_qkv_w, conv1d_weight, alpha_log, beta, gate,
    norm_weight, o_proj, initial_state, residual, out, final_state,
    *, num_heads_qk, num_heads_v, head_dim_qk, head_dim_v,
    l2_eps=1e-6, norm_eps=1e-5, scale=None,
):
    """Validate metadata without reading tensor values or executing a kernel."""
    if inpx.ndim != 3:
        raise ValueError("inpx must have shape [B,S,M]")
    b, s, m = inpx.shape
    hq, hv, dk, dv = num_heads_qk, num_heads_v, head_dim_qk, head_dim_v
    if min(b, s, m, hq, hv, dk, dv) < 1 or hv % hq:
        raise ValueError("Dimensions must be positive and Hv must be divisible by Hqk")
    if l2_eps <= 0 or norm_eps <= 0 or not math.isfinite(l2_eps + norm_eps):
        raise ValueError("Normalization epsilons must be positive and finite")
    if scale is not None and not math.isfinite(scale):
        raise ValueError("scale must be finite")
    c = 2 * hq * dk + hv * dv
    act = inpx.dtype
    if act not in (torch.float16, torch.bfloat16, torch.float32):
        raise ValueError("Activation dtype must be float16, bfloat16, or float32")
    if conv1d_weight.ndim != 3 or conv1d_weight.shape[:2] != (c, 1) or conv1d_weight.shape[2] < 1:
        raise ValueError("conv1d_weight must have shape [C,1,Kc], Kc >= 1")
    tensors = {
        "inpx": (inpx, (b, s, m), act),
        "in_proj_qkv_w": (in_proj_qkv_w, (m, c), act),
        "conv1d_weight": (conv1d_weight, tuple(conv1d_weight.shape), act),
        "alpha_log": (alpha_log, (b, s, hv, dk), torch.float32),
        "beta": (beta, (b, s, hv), act),
        "gate": (gate, (b, s, hv, dv), act),
        "norm_weight": (norm_weight, (dv,), act),
        "o_proj": (o_proj, (hv * dv, m), act),
        "initial_state": (initial_state, (b, hv, dk, dv), torch.float32),
        "residual": (residual, (b, s, m), act),
        "out": (out, (b, s, m), act),
        "final_state": (final_state, (b, hv, dk, dv), torch.float32),
    }
    for name, (tensor, shape, dtype) in tensors.items():
        if tuple(tensor.shape) != shape or tensor.dtype != dtype:
            raise ValueError(f"{name}: expected shape={shape}, dtype={dtype}")
        if tensor.device != inpx.device or not tensor.is_contiguous():
            raise ValueError(f"{name}: tensors must share a device and be contiguous")
    if inpx.device.type != "meta":
        inputs = [t[0] for name, t in tensors.items() if name not in ("out", "final_state")]
        input_storage = {t.untyped_storage().data_ptr() for t in inputs}
        outputs = [out.untyped_storage().data_ptr(), final_state.untyped_storage().data_ptr()]
        if len(set(outputs)) != 2 or any(p in input_storage for p in outputs):
            raise ValueError("Output buffers must not alias any input or each other")


def _recurrent_kda(q, k, v, alpha_log, beta, initial_state, scale):
    """Apply decay, delta correction, and the query after each state update."""
    state = initial_state.float().clone()
    result = torch.empty_like(v, dtype=torch.float32)
    for token in range(q.shape[1]):
        kt = k[:, token].float()
        state = state * alpha_log[:, token].float().exp().unsqueeze(-1)
        prediction = (kt.unsqueeze(-1) * state).sum(dim=-2)
        update = beta[:, token].float().unsqueeze(-1) * (v[:, token].float() - prediction)
        state = state + kt.unsqueeze(-1) * update.unsqueeze(-2)
        result[:, token] = scale * (q[:, token].float().unsqueeze(-1) * state).sum(dim=-2)
    return result, state


@torch.no_grad()
def reference(
    inpx: torch.Tensor,
    in_proj_qkv_w: torch.Tensor,
    conv1d_weight: torch.Tensor,
    alpha_log: torch.Tensor,
    beta: torch.Tensor,
    gate: torch.Tensor,
    norm_weight: torch.Tensor,
    o_proj: torch.Tensor,
    initial_state: torch.Tensor,
    residual: torch.Tensor,
    out: torch.Tensor,
    final_state: torch.Tensor,
    *,
    num_heads_qk: int,
    num_heads_v: int,
    head_dim_qk: int,
    head_dim_v: int,
    l2_eps: float = 1e-6,
    norm_eps: float = 1e-5,
    scale: float | None = None,
) -> None:
    """Write out[B,S,M] and final_state[B,Hv,Dk,Dv] using caller buffers.

    All other tensors are read-only. alpha_log is the natural-log decay;
    beta and gate are materialized inputs, not generated by this function.
    See README.md for every parameter, equation, and rounding boundary.
    """
    validate_arguments(
        inpx, in_proj_qkv_w, conv1d_weight, alpha_log, beta, gate,
        norm_weight, o_proj, initial_state, residual, out, final_state,
        num_heads_qk=num_heads_qk, num_heads_v=num_heads_v,
        head_dim_qk=head_dim_qk, head_dim_v=head_dim_v,
        l2_eps=l2_eps, norm_eps=norm_eps, scale=scale,
    )
    if inpx.device.type == "meta":
        raise ValueError("Meta tensors support input validation only")
    b, s, _ = inpx.shape
    hq, hv, dk, dv = num_heads_qk, num_heads_v, head_dim_qk, head_dim_v
    act = inpx.dtype
    scale = dk ** -0.5 if scale is None else scale

    # Match the module boundaries: projection, causal depthwise convolution, SiLU.
    projected = (inpx.float() @ in_proj_qkv_w.float()).to(act)
    width = conv1d_weight.shape[-1]
    convolved = F.conv1d(
        projected.transpose(1, 2).float(), conv1d_weight.float(),
        padding=width - 1, groups=conv1d_weight.shape[0],
    )[:, :, :s]
    packed = F.silu(convolved).transpose(1, 2).to(act)
    q, k, v = packed.split((hq * dk, hq * dk, hv * dv), dim=-1)
    q, k = q.reshape(b, s, hq, dk).float(), k.reshape(b, s, hq, dk).float()
    q = (q * torch.rsqrt(q.square().sum(-1, keepdim=True) + l2_eps)).to(act)
    k = (k * torch.rsqrt(k.square().sum(-1, keepdim=True) + l2_eps)).to(act)
    q = q.repeat_interleave(hv // hq, dim=2)
    k = k.repeat_interleave(hv // hq, dim=2)
    v = v.reshape(b, s, hv, dv)

    attention, state = _recurrent_kda(q, k, v, alpha_log, beta, initial_state, scale)
    attention = attention.to(act).float()
    normalized = attention * torch.rsqrt(attention.square().mean(-1, keepdim=True) + norm_eps)
    normalized = (normalized * norm_weight.float() * gate.float().sigmoid()).to(act)
    projected_out = normalized.reshape(b, s, hv * dv).float() @ o_proj.float()
    out.copy_((projected_out + residual.float()).to(act))
    final_state.copy_(state)
